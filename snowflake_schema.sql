---------------- DIM DATE TABLE--------------------------

CREATE OR REPLACE TABLE DIM_DATE AS
SELECT DISTINCT
    RIDE_DATE AS DATE_KEY,
    RIDE_DATE,
    YEAR(RIDE_DATE) AS YEAR,
    MONTH(RIDE_DATE) AS MONTH,
    DAY(RIDE_DATE) AS DAY,
    DAYNAME(RIDE_DATE) AS DAY_NAME,
    WEEKOFYEAR(RIDE_DATE) AS WEEK_OF_YEAR,
    QUARTER(RIDE_DATE) AS QUARTER
FROM STREAM_DATABASE.SILVER.CAB_RIDES_SILVER
WHERE RIDE_DATE IS NOT NULL;

SELECT * FROM DIM_DATE;

-------------------------DIM DRIVER -----------------------

CREATE OR REPLACE TABLE DIM_DRIVER AS
SELECT DISTINCT
    driver_id,
    driver_name,
    driver_rating,
    driver_license
FROM STREAM_DATABASE.SILVER.CAB_RIDES_SILVER
WHERE driver_id IS NOT NULL;


CREATE OR REPLACE TABLE DIM_VEHICLE AS
SELECT DISTINCT
    VEHICLE_ID,
    VEHICLE_TYPE_ID,
    VEHICLE_MAKE_ID,
    VEHICLE_MODEL,
    VEHICLE_COLOR
FROM STREAM_DATABASE.SILVER.CAB_RIDES_SILVER
WHERE VEHICLE_ID IS NOT NULL;

SELECT * FROM DIM_VEHICLE;

