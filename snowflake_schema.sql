CREATE OR REPLACE TABLE DIM_LOCATION AS
 
SELECT DISTINCT
    PICKUP_LOCATION_ID AS LOCATION_ID,
    PICKUP_CITY_ID AS CITY_ID,
    PICKUP_ADDRESS AS ADDRESS,
    PICKUP_LATITUDE AS LATITUDE,
    PICKUP_LONGITUDE AS LONGITUDE
FROM STREAM_DATABASE.SILVER.CAB_RIDES_SILVER
WHERE PICKUP_LOCATION_ID IS NOT NULL
 
UNION
 
SELECT DISTINCT
    DROPOFF_LOCATION_ID AS LOCATION_ID,
    DROPOFF_CITY_ID AS CITY_ID,
    DROPOFF_ADDRESS AS ADDRESS,
    DROPOFF_LATITUDE AS LATITUDE,
    DROPOFF_LONGITUDE AS LONGITUDE
FROM STREAM_DATABASE.SILVER.CAB_RIDES_SILVER
WHERE DROPOFF_LOCATION_ID IS NOT NULL;


SELECT * FROM DIM_LOCATION;

